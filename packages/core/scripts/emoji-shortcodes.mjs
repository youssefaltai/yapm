// Writes src/emoji-shortcodes.ts from @emoji-mart/data: every shortcode and alias with its emoji.
// Run with `node scripts/emoji-shortcodes.mjs` after upgrading @emoji-mart/data.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const data = JSON.parse(
  readFileSync(require.resolve("@emoji-mart/data/sets/15/native.json"), "utf8"),
);
const pairs = Object.values(data.emojis).map((e) => `${e.id} ${e.skins[0].native}`);
for (const [alias, id] of Object.entries(data.aliases)) {
  const emoji = data.emojis[id];
  if (emoji) pairs.push(`${alias} ${emoji.skins[0].native}`);
}
const version = JSON.parse(
  readFileSync(require.resolve("@emoji-mart/data/package.json"), "utf8"),
).version;
writeFileSync(
  new URL("../src/emoji-shortcodes.ts", import.meta.url),
  `// Generated by scripts/emoji-shortcodes.mjs from @emoji-mart/data ${version}. Do not edit.\n` +
    "/** Slack and GitHub style shortcodes and their emoji, as space-separated pairs. */\n" +
    `export const SHORTCODES = ${JSON.stringify(pairs.join(" "))};\n`,
);
